// 建议5：导入独立分区渲染；数据与安全不再含导入；ME_TABS 含 import/feedback
var A = globalThis.NOVEL_APP;
var V = globalThis.NOVEL_VIEWS;
var wait = function (ms) { return new Promise(function (r) { setTimeout(r, ms); }); };
var out = {};
out.tabs = (V.ME_TABS || []).map(function (t) { return t.key; });
A.go('#/me/import'); await wait(800);
out.importRadios = document.querySelectorAll('input[name="impMode"]').length;
out.importHasTitle = !!document.getElementById('impTitle');
out.importHasBody = !!document.getElementById('impBody');
out.importHasPreCheck = !!document.getElementById('preCheckBtn');
out.importHasDo = !!document.getElementById('doImport');
out.doDisabledAtStart = document.getElementById('doImport') ? document.getElementById('doImport').disabled : null;
var mergeR = document.querySelector('input[name="impMode"][value="merge"]');
out.mergeDisabled = mergeR ? mergeR.disabled : 'no-merge-radio';
out.fldBookHiddenInNew = document.getElementById('fldBook') ? document.getElementById('fldBook').hidden : null;
A.go('#/me/data'); await wait(800);
out.dataHasImportControls = !!document.getElementById('preCheckBtn') || !!document.querySelector('input[name="impMode"]');
out.dataHasBackup = !!document.getElementById('backupBtn');
return JSON.stringify(out);
